"""Regenerate the core results of the paper and compare them with the committed SHA-256 manifest.

    python -I replication/run_all.py [--only STEP ...] [--root DIR] [--work DIR] [--keep]
    python -I replication/run_all.py --list
    python -I replication/run_all.py --write-manifest      (maintainer: hash the committed files)

The repository's code, data and committed results are copied to a fresh working folder (a
temporary folder unless ``--work`` is given), so nothing in the repository is changed.  Each
step deletes its own output files in that copy, runs the repository's ``run_*.py`` script with
this interpreter in isolated mode (``-I``), and hashes what the script wrote.  The hashes are
compared with ``replication/expected_sha256.txt``, which holds the hashes of the committed
result files.  See REPLICATION.md for the steps, the run times and the comparison modes:

* ``sha256``: the file's bytes, with CRLF line ends read as LF;
* ``json-stable``: the JSON with timing, memory and platform fields removed (``VOLATILE_KEY``),
  re-serialised with sorted keys;
* ``csv-stable``: the CSV without its timing and memory columns;
* ``md-stable``: the Markdown with every number on a line that reports a time masked;
* ``stdout-stable``: the script's printed report without the timing sections and file paths,
  compared with ``replication/expected/<step>_stdout.txt``.

The corpus steps need the public DMN sources next to the repository (``--root``, default the
repository's parent folder, as filled by ``python -I fetch_corpus.py``); without them they are
reported as skipped.  Exit status 0 when every checked file matches.  Standard library only.
"""
import argparse
import csv
import glob
import hashlib
import io
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MANIFEST = os.path.join(HERE, "expected_sha256.txt")
EXPECTED = os.path.join(HERE, "expected")
COPY = ["latc_check", "data", "results", "fetch_corpus.py"]  # plus every run_*.py

# A JSON key or CSV column whose name matches this holds a time, a memory figure or the platform.
VOLATILE_KEY = re.compile(r"(^|_)(s|ms|ns|us|seconds|mib|kib|gib|python|platform)$")
# JSON top-level sections that are not regenerated by the default runs
SKIP_SECTIONS = {"results/results.json": ["large"]}


def step(name, script, args, outputs, what, needs=None, minutes=1):
    return {"name": name, "script": script, "args": args, "outputs": outputs, "what": what,
            "needs": needs or [], "minutes": minutes}


